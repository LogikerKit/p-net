import assert from 'node:assert/strict';

export function rows(text, scope) {
  const result = text.split('\n').filter(line => line.startsWith('ALARM_MODEL_JSON '))
    .map(line => JSON.parse(line.slice('ALARM_MODEL_JSON '.length)));
  assert(result.every(row => row.scope === scope), 'Unexpected native scope');
  const ids = result.map(row => row.id);
  assert.equal(new Set(ids).size, result.length, 'Duplicate native case');
  return result;
}

export function header(cases, scope) {
  const fields = scope === 'parser' ?
    'bool separate; unsigned mutation; bool accepted;' :
    'bool separate; int send_result; unsigned first_callbacks; unsigned retry_callbacks; unsigned next_sequence;';
  const name = scope === 'parser' ? 'ParserCase' : 'RecoveryCase';
  return '/* Generated by Emit.lean; do not edit. */\n#include <stdint.h>\n' +
    `struct ${name} { unsigned id; uint8_t status[4]; ${fields} };\n` +
    `static const ${name} ${scope}_cases[] = {\n` +
    cases.map(c => {
      const tail = scope === 'parser' ? [c.separate, c.mutation, c.accepted] :
        [c.separate, c.send_result, c.first_callbacks, c.retry_callbacks, c.next_sequence];
      return `{${c.id},{${c.status.join(',')}},${tail.join(',')}},`;
    }).join('\n') + '\n};\n';
}

export function compare(cases, actual, scope) {
  assert.equal(actual.length, cases.length, 'Incomplete native history corpus');
  const map = new Map(actual.map(row => [row.id, row]));
  assert.equal(map.size, cases.length, 'Duplicate native case');
  const differences = [];
  for(const c of cases) {
    const a = map.get(c.id);
    assert(a && a.scope === scope, 'Missing or misrouted native case');
    assert.match(a.frame_hex, /^(?:[0-9a-f]{2})+$/);
    assert(Number.isInteger(a.block_offset) && a.block_offset >= 16);
    const frame = Buffer.from(a.frame_hex, 'hex');
    assert(a.block_offset <= frame.length);
    const block = [...frame.subarray(a.block_offset)];
    const advertised = frame.readUInt16BE(a.block_offset - 2);
    if(scope === 'parser') {
      assert.deepEqual(block, c.block, 'Native/Lean mutation or body disagreement');
      assert.equal(advertised, c.advertised, 'Native/Lean advertised length disagreement');
    } else {
      assert.equal(block.length, 22);
      assert.deepEqual(block.slice(0, 6), [0x80, 1, 0, 18, 1, 0]);
      assert.equal(advertised, 22);
      assert.deepEqual(block.slice(-4), c.status);
      const tack = Buffer.from(a.tack_hex, 'hex');
      assert.equal(a.first_send_result, c.send_result === 1 ? tack.length : c.send_result,
        'Fault did not reach the intended post-construction send boundary');
      assert.equal(a.attempted_tacks, 3, 'Missing original or duplicate TACK');
      assert.equal(a.retry_send_results.length, 2);
      assert(a.retry_send_results.every(value => value === tack.length),
        'Fault leaked into retry sends');
    }
    const expected = scope === 'parser' ? {
      first_callbacks: c.accepted ? 1 : 0,
      first_sequence: c.accepted ? 0 : 65535,
      first_tacks: c.accepted ? 1 : 0,
      callbacks: 1, status: c.status, rejected_without_effects: true,
      duplicate_suppressed: true, next_sent: true,
    } : {
      first_callbacks: c.first_callbacks, retry_callbacks: c.retry_callbacks,
      callbacks: c.retry_callbacks, first_sequence: c.next_sequence,
      status: c.status, next_sent: true,
    };
    for(const [field, value] of Object.entries(expected))
      if(JSON.stringify(a[field]) !== JSON.stringify(value))
        differences.push({id: c.id, field, expected: value, actual: a[field]});
  }
  return differences;
}

export function auditAxioms(log, count) {
  const lines = log.split('\n').filter(line =>
    line.includes('depends on axioms:') || line.includes('does not depend on any axioms'));
  assert.equal(lines.length, count, 'Missing theorem axiom audit');
  for(const line of lines) {
    const names = line.match(/\[([^\]]*)\]/)?.[1] ?? '';
    assert(names.split(',').every(name =>
      ['', 'propext', 'Quot.sound', 'Classical.choice'].includes(name.trim())),
      `Unexpected axiom: ${line}`);
  }
}
